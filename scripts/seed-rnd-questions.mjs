// Defaults injected onto every new question.
const COMMON_DEFAULTS = {
  source: "seed",
  bibId: BIB,
};

async function main() {
  const existing = JSON.parse(await readFile(Q_PATH, "utf8"));
  const existingIds = new Set(existing.map((q) => q.id));
  const incoming = [...RE_QS, ...VR_QS];
  let added = 0;
  for (const q of incoming) {
    if (existingIds.has(q.id)) continue;
    existing.push({ ...COMMON_DEFAULTS, ...q });
    existingIds.add(q.id);
    added++;
  }
  await writeFile(Q_PATH, JSON.stringify(existing, null, 2) + "\n", "utf8");
  console.log(`seed-rnd-questions: added ${added} new question(s); total now ${existing.length}.`);
}

main().catch((e) => { console.error("seed-rnd-questions fatal:", e); process.exit(1); });
