async function main() {
  const qs = JSON.parse(await readFile(Q_PATH, "utf8"));
  const ids = new Set(qs.map((q) => q.id));

  // Apply slug fixes to round-one R&D questions.
  let fixed = 0;
  for (const q of qs) {
    const fix = SLUG_FIXES[q.id];
    if (fix && q.sourceSection !== fix) {
      q.sourceSection = fix;
      fixed++;
    }
  }

  let added = 0;
  for (const q of [...RE_QS, ...VR_QS]) {
    if (ids.has(q.id)) continue;
    qs.push({ ...COMMON, ...q });
    ids.add(q.id);
    added++;
  }

  await writeFile(Q_PATH, JSON.stringify(qs, null, 2) + "\n", "utf8");
  console.log(`seed-rnd-questions-2: added=${added}, sourceSection fixes=${fixed}, total now ${qs.length}`);
}

