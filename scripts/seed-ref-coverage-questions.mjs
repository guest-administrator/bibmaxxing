function addCehToSecurityObjective(bib) {
  const obj = (bib.objectives || []).find((o) => o.id === "obj-sec-cert-fundamentals");
  if (!obj) return false;
  if (!Array.isArray(obj.sourceRefs)) obj.sourceRefs = [];
  if (obj.sourceRefs.includes("BOOK-CEH")) return false;
  obj.sourceRefs.push("BOOK-CEH");
  return true;
}

